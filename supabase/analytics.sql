create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
  select coalesce((auth.jwt() ->> 'email') = 'bastianhochreither@gmx.at', false);
$$;

create table if not exists public.daily_analytics (
  id bigint generated by default as identity primary key,
  date date not null unique,
  visitors integer not null default 0 check (visitors >= 0),
  page_views integer not null default 0 check (page_views >= 0),
  contact_requests integer not null default 0 check (contact_requests >= 0),
  configurations_started integer not null default 0 check (configurations_started >= 0),
  configurations_submitted integer not null default 0 check (configurations_submitted >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.page_analytics (
  id bigint generated by default as identity primary key,
  date date not null,
  page_path text not null,
  view_count integer not null default 0 check (view_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists page_analytics_date_page_path_idx
on public.page_analytics (date, page_path);

create table if not exists public.model_analytics (
  id bigint generated by default as identity primary key,
  date date not null,
  model_id text not null,
  model_name text not null default '',
  view_count integer not null default 0 check (view_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists model_analytics_date_model_id_idx
on public.model_analytics (date, model_id);

create table if not exists public.visitor_analytics (
  id bigint generated by default as identity primary key,
  date date not null,
  language text not null default 'de',
  device_type text not null default 'desktop',
  source text not null default 'unknown',
  "count" integer not null default 0 check ("count" >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint visitor_analytics_language_check check (language in ('de', 'en', 'sk')),
  constraint visitor_analytics_device_type_check check (device_type in ('desktop', 'tablet', 'mobile')),
  constraint visitor_analytics_source_check check (source in ('google', 'direct', 'external', 'unknown'))
);

create unique index if not exists visitor_analytics_daily_dimension_idx
on public.visitor_analytics (date, language, device_type, source);

alter table public.daily_analytics enable row level security;
alter table public.page_analytics enable row level security;
alter table public.model_analytics enable row level security;
alter table public.visitor_analytics enable row level security;

revoke all on table public.daily_analytics from anon, authenticated;
revoke all on table public.page_analytics from anon, authenticated;
revoke all on table public.model_analytics from anon, authenticated;
revoke all on table public.visitor_analytics from anon, authenticated;

grant select on table public.daily_analytics to authenticated;
grant select on table public.page_analytics to authenticated;
grant select on table public.model_analytics to authenticated;
grant select on table public.visitor_analytics to authenticated;

