create or replace function public.track_analytics_event(
  p_event_type text,
  p_event_date date default current_date,
  p_page_path text default null,
  p_model_id text default null,
  p_model_name text default null,
  p_language text default 'de',
  p_device_type text default 'desktop',
  p_source text default 'unknown',
  p_count_visitor boolean default false
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_type text := lower(trim(coalesce(p_event_type, '')));
  v_date date := coalesce(p_event_date, current_date);
  v_page_path text := nullif(left(trim(coalesce(p_page_path, '')), 120), '');
  v_model_id text := nullif(left(trim(coalesce(p_model_id, '')), 120), '');
  v_model_name text := left(trim(coalesce(p_model_name, '')), 160);
  v_language text := case when p_language in ('de', 'en', 'sk') then p_language else 'de' end;
  v_device_type text := case when p_device_type in ('desktop', 'tablet', 'mobile') then p_device_type else 'desktop' end;
  v_source text := case when p_source in ('google', 'direct', 'external', 'unknown') then p_source else 'unknown' end;
begin
  if v_event_type not in (
    'page_view',
    'model_view',
    'contact_request',
    'configuration_started',
    'configuration_submitted'
  ) then
    return;
  end if;

  insert into public.daily_analytics (
    date,
    visitors,
    page_views,
    contact_requests,
    configurations_started,
    configurations_submitted
  )
  values (
    v_date,
    case when v_event_type = 'page_view' and p_count_visitor then 1 else 0 end,
    case when v_event_type = 'page_view' then 1 else 0 end,
    case when v_event_type = 'contact_request' then 1 else 0 end,
    case when v_event_type = 'configuration_started' then 1 else 0 end,
    case when v_event_type = 'configuration_submitted' then 1 else 0 end
  )
  on conflict (date) do update set
    visitors = public.daily_analytics.visitors + excluded.visitors,
    page_views = public.daily_analytics.page_views + excluded.page_views,
    contact_requests = public.daily_analytics.contact_requests + excluded.contact_requests,
    configurations_started = public.daily_analytics.configurations_started + excluded.configurations_started,
    configurations_submitted = public.daily_analytics.configurations_submitted + excluded.configurations_submitted,
    updated_at = now();

  if v_event_type = 'page_view' and v_page_path is not null then
    insert into public.page_analytics (date, page_path, view_count)
    values (v_date, v_page_path, 1)
    on conflict (date, page_path) do update set
      view_count = public.page_analytics.view_count + 1,
      updated_at = now();
  end if;

  if v_event_type = 'page_view' and p_count_visitor then
    insert into public.visitor_analytics (date, language, device_type, source, "count")
    values (v_date, v_language, v_device_type, v_source, 1)
    on conflict (date, language, device_type, source) do update set
      "count" = public.visitor_analytics."count" + 1,
      updated_at = now();
  end if;

  if v_event_type = 'model_view' and v_model_id is not null then
    insert into public.model_analytics (date, model_id, model_name, view_count)
    values (v_date, v_model_id, v_model_name, 1)
    on conflict (date, model_id) do update set
      model_name = excluded.model_name,
      view_count = public.model_analytics.view_count + 1,
      updated_at = now();
  end if;
end;
$$;

revoke all on function public.track_analytics_event(
  text,
  date,
  text,
  text,
  text,
  text,
  text,
  text,
  boolean
) from public;

