create or replace function public.claim_due_customer_reminders(p_limit integer default 20)
returns table (
  customer_id bigint,
  reminder_stage text,
  customer_name text,
  customer_email text,
  preferred_language text,
  purchased_item text,
  purchase_date date
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with due as (
    select
      c.id,
      case
        when c.two_month_email_status in ('pending', 'failed')
          and c.two_month_email_attempts < 3
          and (c.two_month_email_attempted_at is null or c.two_month_email_attempted_at < now() - interval '1 day')
          and (c.purchase_date + interval '2 months')::date <= (now() at time zone 'Europe/Vienna')::date
          then 'two_month'
        when c.six_month_email_status in ('pending', 'failed')
          and c.six_month_email_attempts < 3
          and (c.six_month_email_attempted_at is null or c.six_month_email_attempted_at < now() - interval '1 day')
          and (c.purchase_date + interval '6 months')::date <= (now() at time zone 'Europe/Vienna')::date
          then 'six_month'
        when c.twelve_month_email_status in ('pending', 'failed')
          and c.twelve_month_email_attempts < 3
          and (c.twelve_month_email_attempted_at is null or c.twelve_month_email_attempted_at < now() - interval '1 day')
          and (c.purchase_date + interval '12 months')::date <= (now() at time zone 'Europe/Vienna')::date
          then 'twelve_month'
        else null
      end as stage
    from public.customers c
    where c.deleted_at is null
      and c.follow_up_enabled = true
      and c.follow_up_opt_out = false
      and c.follow_up_permission_status in ('consented', 'existing_customer_permitted')
      and c.review_status = 'none'
      and c.review_found_at is null
      and c.manual_review_confirmed_at is null
      and not (c.twelve_month_email_status = 'sent' or c.twelve_month_email_sent_at is not null)
    order by c.purchase_date asc, c.id asc
    limit least(greatest(coalesce(p_limit, 20), 1), 50)
    for update skip locked
  ),
  selected_due as (
    select due.id, due.stage
    from due
    where due.stage is not null
  ),
  updated as (
    update public.customers c
    set
      two_month_email_status = case when selected_due.stage = 'two_month' then 'processing' else c.two_month_email_status end,
      two_month_email_attempted_at = case when selected_due.stage = 'two_month' then now() else c.two_month_email_attempted_at end,
      two_month_email_attempts = case when selected_due.stage = 'two_month' then c.two_month_email_attempts + 1 else c.two_month_email_attempts end,
      six_month_email_status = case when selected_due.stage = 'six_month' then 'processing' else c.six_month_email_status end,
      six_month_email_attempted_at = case when selected_due.stage = 'six_month' then now() else c.six_month_email_attempted_at end,
      six_month_email_attempts = case when selected_due.stage = 'six_month' then c.six_month_email_attempts + 1 else c.six_month_email_attempts end,
      twelve_month_email_status = case when selected_due.stage = 'twelve_month' then 'processing' else c.twelve_month_email_status end,
      twelve_month_email_attempted_at = case when selected_due.stage = 'twelve_month' then now() else c.twelve_month_email_attempted_at end,
      twelve_month_email_attempts = case when selected_due.stage = 'twelve_month' then c.twelve_month_email_attempts + 1 else c.twelve_month_email_attempts end
    from selected_due
    where c.id = selected_due.id
    returning
      c.id,
      selected_due.stage,
      c.name,
      c.email,
      c.preferred_language,
      c.purchased_item,
      c.purchase_date
  )
  select
    updated.id,
    updated.stage,
    updated.name,
    updated.email,
    updated.preferred_language,
    updated.purchased_item,
    updated.purchase_date
  from updated;
end;
$$;

revoke all on function public.claim_due_customer_reminders(integer) from public;
grant execute on function public.claim_due_customer_reminders(integer) to service_role;

create or replace function public.record_customer_reminder_result(
  p_customer_id bigint,
  p_stage text,
  p_status text,
  p_error_code text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_status not in ('sent', 'failed', 'skipped') then
    return false;
  end if;

  if p_stage = 'two_month' then
    update public.customers
    set
      two_month_email_status = p_status,
      two_month_email_sent_at = case when p_status = 'sent' then now() else two_month_email_sent_at end
    where id = p_customer_id;
  elsif p_stage = 'six_month' then
    update public.customers
    set
      six_month_email_status = p_status,
      six_month_email_sent_at = case when p_status = 'sent' then now() else six_month_email_sent_at end
    where id = p_customer_id;
  elsif p_stage = 'twelve_month' then
    update public.customers
    set
      twelve_month_email_status = p_status,
      twelve_month_email_sent_at = case when p_status = 'sent' then now() else twelve_month_email_sent_at end
    where id = p_customer_id;
  else
    return false;
  end if;

  perform public.log_customer_followup_event(
    p_customer_id,
    'reminder_' || p_status,
    p_stage,
    p_status,
    p_error_code
  );

  return true;
end;
$$;

