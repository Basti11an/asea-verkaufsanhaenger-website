create or replace function public.submit_customer_review_with_token(
  p_token text,
  p_rating integer,
  p_beschreibung text,
  p_ort text default '',
  p_public_consent boolean default false
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token_hash text;
  v_token record;
  v_customer record;
  v_reference_id bigint;
  v_description text;
  v_location text;
  v_year integer;
begin
  if p_token is null or length(p_token) < 32 then
    return false;
  end if;

  if p_rating is null or p_rating < 1 or p_rating > 5 then
    return false;
  end if;

  v_description := left(btrim(coalesce(p_beschreibung, '')), 1600);
  v_location := left(btrim(coalesce(p_ort, '')), 120);

  if length(v_description) < 10 then
    return false;
  end if;

  v_token_hash := encode(digest(p_token, 'sha256'), 'hex');

  select id, customer_id, reminder_stage, used_at
  into v_token
  from public.customer_review_tokens
  where token_hash = v_token_hash
  limit 1;

  if not found then
    return false;
  end if;

  if v_token.used_at is not null then
    return true;
  end if;

  update public.customer_review_tokens
  set used_at = now()
  where id = v_token.id
    and used_at is null;

  if not found then
    return true;
  end if;

  select
    id,
    name,
    email,
    email_normalized,
    purchased_item,
    purchase_date
  into v_customer
  from public.customers
  where id = v_token.customer_id
    and deleted_at is null
  limit 1;

  if not found then
    return false;
  end if;

  v_year := coalesce(
    extract(year from v_customer.purchase_date)::integer,
    extract(year from now())::integer
  );

  insert into public.customer_references (
    kundenname,
    ort,
    modell,
    jahr,
    beschreibung,
    bild_url,
    rating,
    public_consent,
    sichtbar,
    status,
    kontakt_email,
    kontakt_telefon,
    customer_id,
    kontakt_email_normalized,
    review_matched_at
  )
  values (
    left(coalesce(nullif(btrim(v_customer.name), ''), 'ASEA Kunde'), 160),
    v_location,
    left(coalesce(nullif(btrim(v_customer.purchased_item), ''), 'ASEA Anhänger'), 180),
    v_year,
    v_description,
    '',
    p_rating,
    coalesce(p_public_consent, false),
    false,
    'pending',
    v_customer.email,
    '',
    v_customer.id,
    v_customer.email_normalized,
    now()
  )
  returning id into v_reference_id;

  update public.customers
  set
    review_status = case when review_status = 'manual_confirmed' then review_status else 'auto_matched' end,
    review_found_at = coalesce(review_found_at, now()),
    review_source = coalesce(review_source, 'asea_website'),
    matched_reference_id = v_reference_id,
    follow_up_enabled = false,
    six_month_email_status = case
      when six_month_email_status in ('pending', 'failed', 'processing') then 'skipped'
      else six_month_email_status
    end,
    twelve_month_email_status = case
      when twelve_month_email_status in ('pending', 'failed', 'processing') then 'skipped'
      else twelve_month_email_status
    end
  where id = v_customer.id;

  perform public.log_customer_followup_event(
    v_customer.id,
    'review_submitted_via_token',
    v_token.reminder_stage,
    null,
    null
  );

  return true;
end;
$$;

