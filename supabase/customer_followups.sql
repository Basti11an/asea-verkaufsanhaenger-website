create or replace function public.unsubscribe_customer_followup(p_token text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token_hash text;
  v_customer_id bigint;
begin
  if p_token is null or length(p_token) < 32 then
    return true;
  end if;

  v_token_hash := encode(digest(p_token, 'sha256'), 'hex');

  select customer_id
  into v_customer_id
  from public.customer_followup_unsubscribe_tokens
  where token_hash = v_token_hash
  limit 1;

  if v_customer_id is null then
    return true;
  end if;

  update public.customer_followup_unsubscribe_tokens
  set used_at = coalesce(used_at, now())
  where token_hash = v_token_hash;

  update public.customers
  set
    follow_up_opt_out = true,
    follow_up_opted_out_at = coalesce(follow_up_opted_out_at, now()),
    follow_up_enabled = false,
    follow_up_permission_status = 'revoked'
  where id = v_customer_id;

  perform public.log_customer_followup_event(v_customer_id, 'customer_opted_out');
  return true;
end;
$$;

revoke all on function public.unsubscribe_customer_followup(text) from public;
grant execute on function public.unsubscribe_customer_followup(text) to anon, authenticated;

