create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  email_normalized text generated always as (lower(btrim(email))) stored,
  purchase_date date not null,
  purchased_item text not null,
  notes text not null default '',
  preferred_language text not null default 'de',
  review_status text not null default 'none',
  review_found_at timestamptz,
  review_source text,
  matched_reference_id bigint,
  manual_review_confirmed_at timestamptz,
  manual_review_source text,
  follow_up_enabled boolean not null default true,
  follow_up_permission_status text not null default 'unknown',
  follow_up_permission_captured_at timestamptz,
  follow_up_permission_source text not null default '',
  follow_up_permission_text_version text not null default '',
  follow_up_permission_information text not null default '',
  follow_up_opt_out boolean not null default false,
  follow_up_opted_out_at timestamptz,
  two_month_email_status text not null default 'pending',
  two_month_email_sent_at timestamptz,
  two_month_email_attempted_at timestamptz,
  two_month_email_attempts integer not null default 0,
  six_month_email_status text not null default 'pending',
  six_month_email_sent_at timestamptz,
  six_month_email_attempted_at timestamptz,
  six_month_email_attempts integer not null default 0,
  twelve_month_email_status text not null default 'pending',
  twelve_month_email_sent_at timestamptz,
  twelve_month_email_attempted_at timestamptz,
  twelve_month_email_attempts integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint customers_name_length_check check (length(btrim(name)) between 2 and 160),
  constraint customers_email_check check (
    length(btrim(email)) between 6 and 160
    and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$'
  ),
  constraint customers_purchase_date_check check (
    purchase_date >= date '2000-01-01'
    and purchase_date <= ((now() at time zone 'Europe/Vienna')::date + interval '1 day')::date
  ),
  constraint customers_purchased_item_length_check check (length(btrim(purchased_item)) between 2 and 180),
  constraint customers_notes_length_check check (length(notes) <= 3000),
  constraint customers_preferred_language_check check (preferred_language in ('de', 'en', 'sk')),
  constraint customers_review_status_check check (review_status in ('none', 'auto_matched', 'manual_confirmed')),
  constraint customers_review_source_check check (
    review_source is null
    or review_source in ('asea_website', 'google', 'personal', 'phone', 'other')
  ),
  constraint customers_manual_review_source_check check (
    manual_review_source is null
    or manual_review_source in ('asea_website', 'google', 'personal', 'phone', 'other')
  ),
  constraint customers_permission_status_check check (
    follow_up_permission_status in ('unknown', 'consented', 'existing_customer_permitted', 'revoked', 'blocked')
  ),
  constraint customers_mail_status_check check (
    two_month_email_status in ('pending', 'processing', 'sent', 'failed', 'skipped')
    and six_month_email_status in ('pending', 'processing', 'sent', 'failed', 'skipped')
    and twelve_month_email_status in ('pending', 'processing', 'sent', 'failed', 'skipped')
  ),
  constraint customers_attempts_check check (
    two_month_email_attempts between 0 and 3
    and six_month_email_attempts between 0 and 3
    and twelve_month_email_attempts between 0 and 3
  )
);

