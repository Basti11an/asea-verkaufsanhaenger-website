create or replace function public.audit_customer_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_type text;
begin
  if tg_op = 'INSERT' then
    perform public.log_customer_followup_event(new.id, 'customer_created');
    return new;
  end if;

  if tg_op = 'DELETE' then
    insert into public.customer_followup_events (customer_id, event_type, actor_user_id)
    values (old.id, 'customer_deleted', auth.uid());
    return old;
  end if;

  v_event_type := case
    when old.follow_up_enabled is distinct from new.follow_up_enabled
      then case when new.follow_up_enabled then 'follow_up_enabled' else 'follow_up_disabled' end
    when old.follow_up_permission_status is distinct from new.follow_up_permission_status
      then 'permission_status_changed'
    when old.review_status is distinct from new.review_status
      then case when new.review_status = 'manual_confirmed' then 'review_manually_confirmed' else 'review_status_changed' end
    when old.follow_up_opt_out is distinct from new.follow_up_opt_out and new.follow_up_opt_out = true
      then 'customer_opted_out'
    else 'customer_updated'
  end;

  perform public.log_customer_followup_event(new.id, v_event_type);
  return new;
end;
$$;

drop trigger if exists audit_customer_change on public.customers;
create trigger audit_customer_change
after insert or update or delete on public.customers
for each row
execute function public.audit_customer_change();

create or replace function public.prepare_reference_customer_match()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id bigint;
begin
  new.kontakt_email_normalized := lower(btrim(coalesce(new.kontakt_email, '')));

  if new.kontakt_email_normalized = '' then
    new.customer_id := null;
    return new;
  end if;

  select c.id
  into v_customer_id
  from public.customers c
  where c.email_normalized = new.kontakt_email_normalized
    and c.deleted_at is null
  order by c.id asc
  limit 1;

  if v_customer_id is not null then
    new.customer_id := v_customer_id;
    new.review_matched_at := coalesce(new.review_matched_at, now());
  end if;

  return new;
end;
$$;

drop trigger if exists prepare_reference_customer_match on public.customer_references;
create trigger prepare_reference_customer_match
before insert or update of kontakt_email on public.customer_references
for each row
execute function public.prepare_reference_customer_match();

create or replace function public.apply_reference_customer_match()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.customer_id is null then
    return new;
  end if;

  update public.customers
  set
    review_status = case when review_status = 'manual_confirmed' then review_status else 'auto_matched' end,
    review_found_at = coalesce(review_found_at, now()),
    review_source = coalesce(review_source, 'asea_website'),
    matched_reference_id = new.id
  where id = new.customer_id
    and deleted_at is null
    and follow_up_opt_out = false;

  perform public.log_customer_followup_event(new.customer_id, 'review_auto_matched');
  return new;
end;
$$;

