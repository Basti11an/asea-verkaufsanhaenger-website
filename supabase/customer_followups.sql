create or replace function public.rematch_customer_references_for_customer()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reference_id bigint;
begin
  if new.deleted_at is not null then
    return new;
  end if;

  update public.customer_references
  set kontakt_email_normalized = lower(btrim(coalesce(kontakt_email, '')))
  where kontakt_email is not null
    and coalesce(kontakt_email_normalized, '') <> lower(btrim(coalesce(kontakt_email, '')));

  update public.customer_references
  set customer_id = null
  where customer_id = new.id
    and coalesce(kontakt_email_normalized, '') <> new.email_normalized;

  update public.customer_references
  set
    customer_id = new.id,
    review_matched_at = coalesce(review_matched_at, now())
  where kontakt_email_normalized = new.email_normalized
    and coalesce(kontakt_email_normalized, '') <> ''
    and (customer_id is null or customer_id = new.id);

  select id
  into v_reference_id
  from public.customer_references
  where customer_id = new.id
  order by created_at desc, id desc
  limit 1;

  if v_reference_id is not null then
    update public.customers
    set
      review_status = case when review_status = 'manual_confirmed' then review_status else 'auto_matched' end,
      review_found_at = coalesce(review_found_at, now()),
      review_source = coalesce(review_source, 'asea_website'),
      matched_reference_id = coalesce(matched_reference_id, v_reference_id)
    where id = new.id
      and deleted_at is null
      and follow_up_opt_out = false;

    perform public.log_customer_followup_event(new.id, 'review_auto_matched');
  end if;

  return new;
end;
$$;

drop trigger if exists rematch_customer_references_for_customer on public.customers;
create trigger rematch_customer_references_for_customer
